#Integer
age = 22
print(age)
print(type(age))

#Float
salary = 25000.00
print(salary)
print(type(salary))

#String
name = "Shubhangi"
print(name)
print(type(name))

#Boolean
is_student = True
print(is_student)
print(type(is_student))

#List
fruits = ["Apple", "Mango", "Banana"]
print(fruits)
print(type(fruits))

#Tuple
numbers = (10, 20, 30)
print(numbers)
print(type(numbers))

#Set
colors = {"Red", "Blue", "Green"}
print(colors)
print(type(colors))

#Dictionary
employee = {
    "name": "Rahul",
    "age": 25,
    "department": "IT"
}
print(employee)
print(type(employee))